import {
  generateColorPalette,
  VIRGO_BRAND_SCALE,
  VIRGO_CHROMATIC_BASES,
  VIRGO_NEUTRAL_SCALE,
} from '@virgo-design/colors';
import { describe, expect, it } from 'vitest';

import { THEME_BUILDER_DEFAULTS } from '../model/defaults';
import type { ExportFormat, ThemeBuilderState } from '../model/types';
import {
  generateCssTheme,
  generateScssTheme,
  generateTailwindTheme,
  generateThemeCode,
} from './export-theme';

const palette = generateColorPalette({
  linked: false,
  model: 'oklch',
  bases: { ...VIRGO_CHROMATIC_BASES },
});

function createState(exportFormat: ExportFormat = 'css'): ThemeBuilderState {
  return {
    ...THEME_BUILDER_DEFAULTS,
    exportFormat,
    semantics: {
      light: { ...THEME_BUILDER_DEFAULTS.semantics.light },
      dark: { ...THEME_BUILDER_DEFAULTS.semantics.dark },
    },
  };
}

describe('theme export generation', () => {
  it('emits all 140 foundation colors before semantic aliases', () => {
    const css = generateCssTheme(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, createState());
    const foundationBlock = css.slice(0, css.indexOf('}'));
    const foundationDeclarations = foundationBlock
      .split('\n')
      .filter((line) => line.startsWith('  --virgo-'));

    expect(foundationDeclarations).toHaveLength(140);
    expect(css).toContain('--virgo-red-50: #FFF8F8;');
    expect(css).toContain('--virgo-brand-500: #1664F9;');
    expect(css).toContain('--virgo-neutral-500: #5E616D;');
  });

  it('maps light and dark semantic recipes to the expected foundation steps', () => {
    const css = generateCssTheme(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, createState());

    expect(css).toContain('--virgo-semantic-primary-soft: var(--virgo-brand-50);');
    expect(css).toContain('--virgo-semantic-primary: var(--virgo-brand-500);');
    expect(css).toContain('--virgo-semantic-primary-active: var(--virgo-brand-700);');
    expect(css).toContain('--virgo-semantic-primary-soft: var(--virgo-brand-900);');
    expect(css).toContain('--virgo-semantic-primary: var(--virgo-brand-400);');
    expect(css).toContain('--virgo-semantic-primary-active: var(--virgo-brand-200);');
  });

  it('sanitizes user-controlled names before placing them in generated code', () => {
    const state = {
      ...createState(),
      themeName: 'Virgo */ injected',
      prefix: '  Virgo Theme!  ',
    };
    const css = generateCssTheme(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, state);

    expect(css).toContain('/* Virgo * / injected · generated by Virgo Design */');
    expect(css).toContain('--virgo-theme-red-50');
    expect(css).not.toContain('/* Virgo */ injected');
  });

  it('dispatches to CSS, SCSS, and Tailwind generators', () => {
    const cssState = createState('css');
    const scssState = createState('scss');
    const tailwindState = createState('tailwind');

    expect(generateThemeCode(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, cssState)).toBe(
      generateCssTheme(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, cssState),
    );
    expect(generateThemeCode(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, scssState)).toBe(
      generateScssTheme(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, scssState),
    );
    expect(generateThemeCode(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, tailwindState)).toBe(
      generateTailwindTheme(palette, VIRGO_BRAND_SCALE, VIRGO_NEUTRAL_SCALE, tailwindState),
    );
  });
});
